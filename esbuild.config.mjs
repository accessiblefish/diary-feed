import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import copyPluginPkg from "@sprout2000/esbuild-copy-plugin";

const { copyPlugin } = copyPluginPkg;
const production = process.argv[2] === "production";

await esbuild.build({
  bundle: true,
  entryPoints: ["src/main.ts"],
  outfile: "main.js",
  format: "cjs",
  target: "es2018",
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  banner: {
    js: "/* THIS IS A GENERATED/BUNDLED FILE BY ESBUILD */",
  },
  logLevel: "info",
  minify: production,
  sourcemap: production ? false : "inline",
  treeShaking: true,
  plugins: [
    copyPlugin({ src: "src/css/styles.css", dest: "styles.css" }),
  ],
});
